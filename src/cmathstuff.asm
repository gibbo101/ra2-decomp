; FUNCTION: GAMEMD 0x007C5EE4
set_control_word	PROC

	push ebp
	mov ebp, esp
	sub esp, 0Ch
	fwait						; synchronize

	fstcw WORD PTR [ebp-2]			; get control word
	fwait						; synchronize

	mov ax, WORD PTR [ebp-2]		; round mode saved
	and eax, 0FFFFh				; set mode
	mov DWORD PTR FPU_FLAG, eax	; back to memory
	leave
	ret

set_control_word	ENDP


